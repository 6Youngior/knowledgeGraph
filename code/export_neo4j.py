"""Export the verified base graph to an inspectable, standalone Cypher file."""
import json
from pathlib import Path

from graph_store import GraphStore, NODE_TYPES, RELATION_SCHEMA

ROOT = Path(__file__).resolve().parents[1]


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def properties(values):
    pairs = []
    for key, value in values.items():
        if value is None:
            continue
        if isinstance(value, dict) or (isinstance(value, list) and any(isinstance(x, dict) for x in value)):
            value = json.dumps(value, ensure_ascii=False)
        pairs.append(f"`{key.replace('`', '``')}`: {literal(value)}")
    return "{" + ", ".join(pairs) + "}"


def export(output=None):
    store = GraphStore(ROOT / "data", persist=False)
    lines = ["// FinGraph base snapshot; generated by code/export_neo4j.py",
             "CREATE CONSTRAINT entity_id IF NOT EXISTS FOR (n:Entity) REQUIRE n.id IS UNIQUE;",
             "CREATE CONSTRAINT document_id IF NOT EXISTS FOR (n:Document) REQUIRE n.id IS UNIQUE;"]
    for node in store.nodes.values():
        if node["type"] not in NODE_TYPES:
            raise ValueError("Unknown entity type")
        props = {k: v for k, v in node.items() if k not in {"type", "properties"}}
        props.update(node.get("properties", {}))
        lines.append(f"MERGE (n:Entity:{node['type']} {{id: {literal(node['id'])}}}) SET n += {properties(props)};")
    for document in store.sources.values():
        lines.append(f"MERGE (s:Document {{id: {literal(document['id'])}}}) SET s += {properties(document)};")
    for edge in store.edges.values():
        if edge["type"] not in RELATION_SCHEMA:
            raise ValueError("Unknown relation type")
        props = {k: v for k, v in edge.items() if k not in {"source", "target", "type", "id"}}
        lines.append(f"MATCH (a:Entity {{id: {literal(edge['source'])}}}), (b:Entity {{id: {literal(edge['target'])}}}) "
                     f"MERGE (a)-[r:{edge['type']} {{id: {literal(edge['id'])}}}]->(b) SET r += {properties(props)};")
    path = output or ROOT / "data" / "neo4j" / "import.cypher"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Exported {len(store.nodes)} entities, {len(store.edges)} relations, {len(store.sources)} documents to {path}")


if __name__ == "__main__":
    export()
